from __future__ import annotations


def text_field(name: str, label: str, placeholder: str = "", default_value: str = "", multiline: bool = False) -> dict:
    return {
        "name": name,
        "label": label,
        "placeholder": placeholder,
        "default_value": default_value,
        "multiline": multiline,
    }


def level(
    category_slug: str,
    level_number: int,
    title: str,
    difficulty: str,
    objective: str,
    focus: str,
    fields: list[dict],
    unsafe_query: str,
    safe_query: str,
    hint: str,
    success_explanation: str,
    defense: list[str],
    flag: str,
    simulation: dict,
    preview_datasets: list[str] | None = None,
) -> dict:
    return {
        "id": f"{category_slug}-l{level_number}",
        "level": level_number,
        "title": title,
        "difficulty": difficulty,
        "objective": objective,
        "focus": focus,
        "fields": fields,
        "unsafe_query": unsafe_query,
        "safe_query": safe_query,
        "hint": hint,
        "success_explanation": success_explanation,
        "defense": defense,
        "flag": flag,
        "simulation": simulation,
        "preview_datasets": preview_datasets or [],
    }


def category(slug: str, title: str, difficulty: str, summary: str, accent: str, levels: list[dict]) -> dict:
    return {
        "slug": slug,
        "title": title,
        "difficulty": difficulty,
        "summary": summary,
        "accent": accent,
        "levels": levels,
    }


